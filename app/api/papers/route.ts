import { NextRequest, NextResponse } from 'next/server';
import type { PoolClient } from 'pg';
import { query, getPool } from '@/lib/db';
import { getCurrentUser } from '@/lib/auth';
import { generatePaperEmbedding } from '@/lib/embeddings';

export const dynamic = 'force-dynamic';

export async function GET(req: NextRequest) {
  try {
    const { searchParams } = new URL(req.url);
    const q = searchParams.get('q') || '';
    const topic = searchParams.get('topic') || '';
    const venue = searchParams.get('venue') || '';
    const year = searchParams.get('year') || '';
    const mode = searchParams.get('mode') || 'standard'; // 'standard' or 'fts'

    // If Full-Text Search is specifically requested and query is present
    if (mode === 'fts' && q.trim()) {
      const ftsResults = await query(
        `SELECT p.paper_id, p.title, p.abstract, p.publication_year, p.doi,
                pd.reader_path,
                jc.name AS venue, jc.type AS venue_type, jc.impact_factor,
                ROUND(ts_rank(p.search_vector, websearch_to_tsquery('english', $1))::numeric, 3) AS fts_rank,
                ts_headline('english', coalesce(p.abstract, ''), websearch_to_tsquery('english', $1),
                            'MaxWords=25, MinWords=10, StartSel=<mark class="bg-amber-200 font-semibold">, StopSel=</mark>') AS snippet,
                (SELECT string_agg(r.full_name, ', ' ORDER BY pa.author_position)
                 FROM paper_author pa JOIN researcher r ON r.researcher_id = pa.researcher_id
                 WHERE pa.paper_id = p.paper_id) AS authors,
                (SELECT string_agg(t.name, ', ' ORDER BY t.name)
                 FROM paper_topic pt JOIN topic t ON t.topic_id = pt.topic_id
                 WHERE pt.paper_id = p.paper_id) AS topics
         FROM paper p
         LEFT JOIN journal_conference jc ON jc.venue_id = p.venue_id
         LEFT JOIN paper_document pd ON pd.paper_id = p.paper_id
         WHERE p.search_vector @@ websearch_to_tsquery('english', $1)
         ORDER BY fts_rank DESC
         LIMIT 30`,
        [q.trim()]
      );

      return NextResponse.json({ papers: ftsResults, mode: 'fts' });
    }

    // Standard relational filtered search
    let sql = `
      SELECT p.paper_id, p.title, p.abstract, p.publication_year, p.doi,
             pd.reader_path,
             jc.name AS venue, jc.type AS venue_type, jc.impact_factor,
             (SELECT string_agg(r.full_name, ', ' ORDER BY pa.author_position)
              FROM paper_author pa JOIN researcher r ON r.researcher_id = pa.researcher_id
              WHERE pa.paper_id = p.paper_id) AS authors,
             (SELECT string_agg(t.name, ', ' ORDER BY t.name)
              FROM paper_topic pt JOIN topic t ON t.topic_id = pt.topic_id
              WHERE pt.paper_id = p.paper_id) AS topics,
             (pe.paper_id IS NOT NULL) AS has_embedding
      FROM paper p
      LEFT JOIN journal_conference jc ON jc.venue_id = p.venue_id
      LEFT JOIN paper_embedding pe ON pe.paper_id = p.paper_id
      LEFT JOIN paper_document pd ON pd.paper_id = p.paper_id
      WHERE 1=1
    `;

    const params: any[] = [];

    if (q.trim()) {
      params.push(`%${q.trim()}%`);
      sql += ` AND (p.title ILIKE $${params.length} OR p.abstract ILIKE $${params.length})`;
    }

    if (topic.trim()) {
      params.push(topic.trim());
      sql += ` AND EXISTS (
        SELECT 1 FROM paper_topic pt
        JOIN topic t ON t.topic_id = pt.topic_id
        WHERE pt.paper_id = p.paper_id AND t.name = $${params.length}
      )`;
    }

    if (venue.trim()) {
      params.push(venue.trim());
      sql += ` AND jc.name = $${params.length}`;
    }

    if (year.trim() && !isNaN(parseInt(year, 10))) {
      params.push(parseInt(year, 10));
      sql += ` AND p.publication_year = $${params.length}`;
    }

    sql += ` ORDER BY p.publication_year DESC, p.paper_id DESC LIMIT 50`;

    const rows = await query(sql, params);
    return NextResponse.json({ papers: rows, mode: 'standard' });
  } catch (err: any) {
    console.error('Error fetching papers:', err);
    return NextResponse.json({ error: err.message }, { status: 500 });
  }
}

// Multi-table INSERT DML demonstrating explicit transaction.
// The paper embedding is generated by the real MiniLM model through Python;
// no random or synthetic vector is inserted by this API.
export async function POST(req: NextRequest) {
  let client: PoolClient | null = null;
  let transactionStarted = false;

  try {
    const user = await getCurrentUser();
    if (!user) {
      return NextResponse.json(
        { error: 'Unauthorized: Login required to publish papers' },
        { status: 401 }
      );
    }

    const body = await req.json();
    const title = typeof body.title === 'string' ? body.title.trim() : '';
    const abstract = typeof body.abstract === 'string' ? body.abstract.trim() : '';
    const publicationYear = Number(body.publication_year || new Date().getFullYear());
    const venueName = typeof body.venue_name === 'string' ? body.venue_name.trim() : '';
    const doi = typeof body.doi === 'string' ? body.doi.trim() : '';
    const topicIds = Array.isArray(body.topic_ids)
      ? body.topic_ids.map(Number).filter((value: number) => Number.isInteger(value) && value > 0)
      : [];

    if (!title) {
      return NextResponse.json({ error: 'Paper title is required' }, { status: 400 });
    }
    if (!Number.isInteger(publicationYear) || publicationYear < 1800 || publicationYear > 2200) {
      return NextResponse.json({ error: 'Publication year must be between 1800 and 2200' }, { status: 400 });
    }

    // Generate before opening the SQL transaction so model loading/inference
    // does not hold a database transaction open.
    const embedding = await generatePaperEmbedding(title, abstract);
    const vectorLiteral = `[${embedding.join(',')}]`;

    const pool = getPool();
    client = await pool.connect();
    await client.query('BEGIN');
    transactionStarted = true;

    // 1. Get or create venue if specified.
    let venueId: number | null = null;
    if (venueName) {
      const venueRes = await client.query(
        'SELECT venue_id FROM journal_conference WHERE name = $1',
        [venueName]
      );
      if (venueRes.rows.length > 0) {
        venueId = venueRes.rows[0].venue_id;
      } else {
        const newVenue = await client.query(
          'INSERT INTO journal_conference (name, type) VALUES ($1, $2) RETURNING venue_id',
          [venueName, 'Conference']
        );
        venueId = newVenue.rows[0].venue_id;
      }
    }

    // 2. Insert paper.
    const paperRes = await client.query(
      `INSERT INTO paper (title, abstract, publication_year, venue_id, doi)
       VALUES ($1, $2, $3, $4, $5)
       RETURNING paper_id, title, publication_year, doi`,
      [title, abstract || null, publicationYear, venueId, doi || null]
    );
    const newPaperId = paperRes.rows[0].paper_id;

    // 3. Link the logged-in researcher as the primary/corresponding author.
    await client.query(
      `INSERT INTO paper_author (paper_id, researcher_id, author_position, corresponding_author)
       VALUES ($1, $2, 1, TRUE)`,
      [newPaperId, user.researcher_id]
    );

    // 4. Link selected research topics.
    for (const topicId of topicIds) {
      await client.query(
        `INSERT INTO paper_topic (paper_id, topic_id)
         VALUES ($1, $2) ON CONFLICT DO NOTHING`,
        [newPaperId, topicId]
      );
    }

    // 5. Store the genuine, normalized 384-dimensional MiniLM embedding.
    await client.query(
      `INSERT INTO paper_embedding (paper_id, embedding, embedding_model)
       VALUES ($1, $2::vector, $3)`,
      [newPaperId, vectorLiteral, 'all-MiniLM-L6-v2 (SentenceTransformer-generated)']
    );

    // 6. Recalculate researcher vectors and refresh recommended match rows.
    await client.query('SELECT refresh_researcher_embeddings()');
    await client.query('SELECT generate_matches(5, 0.30)');

    await client.query('COMMIT');
    transactionStarted = false;

    return NextResponse.json({
      success: true,
      message: 'Paper published with a genuine all-MiniLM-L6-v2 embedding.',
      embedding_model: 'all-MiniLM-L6-v2',
      embedding_dimensions: 384,
      paper: paperRes.rows[0],
    });
  } catch (err: any) {
    if (client && transactionStarted) {
      try {
        await client.query('ROLLBACK');
      } catch (rollbackError) {
        console.error('Failed to roll back paper publication:', rollbackError);
      }
    }
    console.error('Error inserting paper:', err);
    return NextResponse.json(
      { error: err.message || 'Failed to create paper' },
      { status: 500 }
    );
  } finally {
    client?.release();
  }
}
