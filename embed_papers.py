#!/usr/bin/env python3
"""Generate real all-MiniLM-L6-v2 embeddings for the papers already in Neon.

This replaces the synthetic seed vectors in paper_embedding, rebuilds each
researcher's profile vector as the mean of their paper vectors, and refreshes
recommended matches. Existing accepted collaboration pairs in match_result are
preserved.

Required environment variable:
    DATABASE_URL=<your Neon PostgreSQL connection string>

Install dependencies:
    python -m pip install -U sentence-transformers "psycopg[binary]" pgvector numpy

Run:
    python embed_papers.py
"""
from __future__ import annotations

import os
import sys

import numpy as np
import psycopg
from pgvector.psycopg import register_vector
from sentence_transformers import SentenceTransformer

MODEL_ID = "sentence-transformers/all-MiniLM-L6-v2"
# Deliberately differs from the old seed-table default so that Neon can
# distinguish embeddings generated by this script from synthetic seed vectors.
PAPER_MODEL_LABEL = "all-MiniLM-L6-v2 (SentenceTransformer-generated)"
RESEARCHER_MODEL_LABEL = "all-MiniLM-L6-v2 (mean of real paper embeddings)"
EXPECTED_DIMENSIONS = 384
BATCH_SIZE = 32


def main() -> int:
    database_url = os.environ.get("DATABASE_URL", "").strip()
    if not database_url:
        print("ERROR: DATABASE_URL is not set in this PowerShell session.", file=sys.stderr)
        return 1

    print(f"Loading embedding model: {MODEL_ID}")
    model = SentenceTransformer(MODEL_ID)

    print("Reading papers from Neon...")
    with psycopg.connect(database_url, connect_timeout=30) as conn:
        register_vector(conn)
        papers = conn.execute(
            """
            SELECT paper_id,
                   concat_ws('. ', title, NULLIF(abstract, '')) AS paper_text
            FROM paper
            ORDER BY paper_id
            """
        ).fetchall()

    if not papers:
        print("ERROR: No papers were found in the connected database.", file=sys.stderr)
        return 1

    paper_ids = [paper_id for paper_id, _ in papers]
    paper_texts = [paper_text for _, paper_text in papers]

    print(f"Generating embeddings for {len(papers)} papers...")
    vectors = model.encode(
        paper_texts,
        batch_size=BATCH_SIZE,
        show_progress_bar=True,
        convert_to_numpy=True,
        normalize_embeddings=True,
    )

    if vectors.shape != (len(papers), EXPECTED_DIMENSIONS):
        print(
            f"ERROR: Expected embeddings with shape ({len(papers)}, "
            f"{EXPECTED_DIMENSIONS}), received {vectors.shape}.",
            file=sys.stderr,
        )
        return 1

    if not np.isfinite(vectors).all():
        print("ERROR: The model produced NaN or infinite vector values.", file=sys.stderr)
        return 1

    print("Writing paper vectors and rebuilding researcher profiles in Neon...")
    with psycopg.connect(database_url, connect_timeout=30) as conn:
        register_vector(conn)

        # The connection context commits all changes on success and rolls them
        # back automatically if any statement fails.
        for paper_id, vector in zip(paper_ids, vectors):
            conn.execute(
                """
                INSERT INTO paper_embedding
                    (paper_id, embedding, embedding_model, generated_at)
                VALUES (%s, %s, %s, CURRENT_TIMESTAMP)
                ON CONFLICT (paper_id) DO UPDATE
                SET embedding = EXCLUDED.embedding,
                    embedding_model = EXCLUDED.embedding_model,
                    generated_at = EXCLUDED.generated_at
                """,
                (paper_id, vector, PAPER_MODEL_LABEL),
            )

        # This SQL function averages the newly generated paper vectors for
        # each researcher who is associated with at least one paper.
        conn.execute("SELECT refresh_researcher_embeddings()")
        conn.execute(
            """
            UPDATE researcher_embedding
            SET embedding_model = %s,
                generated_at = CURRENT_TIMESTAMP
            """,
            (RESEARCHER_MODEL_LABEL,),
        )

        # match_result is used both for generated recommendations and for
        # accepted collaboration pairs. Remove stale recommendations but
        # preserve pairs backed by an Accepted collaboration_request.
        conn.execute(
            """
            DELETE FROM match_result mr
            WHERE NOT EXISTS (
                SELECT 1
                FROM collaboration_request cr
                WHERE cr.status = 'Accepted'
                  AND LEAST(cr.sender_id, cr.receiver_id) = mr.researcher_1_id
                  AND GREATEST(cr.sender_id, cr.receiver_id) = mr.researcher_2_id
            )
            """
        )
        conn.execute("SELECT generate_matches(5, 0.30)")

        paper_count = conn.execute(
            "SELECT COUNT(*) FROM paper_embedding WHERE embedding_model = %s",
            (PAPER_MODEL_LABEL,),
        ).fetchone()[0]
        researcher_count = conn.execute(
            "SELECT COUNT(*) FROM researcher_embedding WHERE embedding_model = %s",
            (RESEARCHER_MODEL_LABEL,),
        ).fetchone()[0]
        match_count = conn.execute("SELECT COUNT(*) FROM match_result").fetchone()[0]

    print("\nSUCCESS: Neon has been updated.")
    print(f"Paper embeddings generated:      {paper_count}")
    print(f"Researcher profile embeddings:   {researcher_count}")
    print(f"Match rows currently stored:     {match_count}")
    print(f"Paper embedding label:           {PAPER_MODEL_LABEL}")
    print(f"Researcher embedding label:      {RESEARCHER_MODEL_LABEL}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
